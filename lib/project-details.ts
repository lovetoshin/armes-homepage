//    여기에는 "상세 페이지에 실제로 써 넣을 설명"만 담는다.
// 작성 원칙(형님 지침): 운영중 = 지금 되는 기능 그대로, 준비중/연구중 = 목표·방향을 솔직하게.

export interface ProjectFeature {
  title: string;
  desc: string;
}

export interface ProjectDetail {
  key: string;
  // 상세 페이지 상단 큰 소개 문단(한두 문장)
  intro: string;
  // 어떤 불편을 푸는가
  problem: string;
  // 핵심 기능/구성
  features: ProjectFeature[];
  // 이런 분께 도움이 됩니다
  forWhom: string[];
  // 상태 안내(준비중/연구중일 때 정직하게)
  statusNote?: string;
  // 외부 앱 버튼에 쓸 라벨(운영중일 때만)
  ctaLabel?: string;
  // 실제 앱 캡처 — 상세 페이지에서 한 줄 갤러리로 표시(장수만큼 열, 최대 6열)
  gallery?: string[];
  // 화면 묶음이 여러 개일 때(예: 리워드톡 국내판·해외판) — 묶음마다 제목을 달아 한 줄씩 보여 준다
  galleries?: { title: string; desc?: string; images: string[] }[];
  // 유료 서비스의 요금·이용기간·취소/환불 규정(결제사 심사용) — 약관과 같은 숫자를 쓴다
  billing?: ProjectBilling;
  // 상세 페이지 맨 아래 약관·방침 바로가기
  legalLinks?: { href: string; label: string; desc: string }[];
}

export interface ProjectBilling {
  plans: { name: string; price: string; desc: string; pay: string }[];
  priceNote: string;
  period: string[];
  refund: string[];
}

// 앱 하나의 이용약관·개인정보 처리방침 바로가기 두 줄
function legal(base: string, name: string): ProjectDetail["legalLinks"] {
  return [
    { href: `/${base}/terms`, label: "이용약관", desc: `${name} 서비스 이용약관을 확인하세요` },
    { href: `/${base}/privacy`, label: "개인정보 처리방침", desc: `${name} 서비스의 개인정보 처리방침을 확인하세요` },
  ];
}

